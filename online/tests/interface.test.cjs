const { test } = require('node:test');
const assert = require('node:assert/strict');
const { JSDOM } = require('jsdom');
const { IDBFactory } = require('fake-indexeddb');
const { readFileSync } = require('node:fs');
const { resolve } = require('node:path');
const { webcrypto } = require('node:crypto');
const vm = require('node:vm');

test('existing interface boots against IndexedDB and renders settings without Go', async () => {
  const root = resolve('../dist/online');
  const html = readFileSync(resolve(root,'index.html'),'utf8');
  const dom = new JSDOM(html,{url:'http://localhost:8080',runScripts:'outside-only',pretendToBeVisual:true});
  const window = dom.window;
  Object.defineProperty(window.navigator,'userAgent',{value:'iPhone'});
  window.scrollTo = () => {};
  Object.defineProperty(window,'indexedDB',{value:new IDBFactory()});
  Object.defineProperty(window,'crypto',{value:webcrypto});
  Object.assign(window,{Response,Headers,Blob,TextEncoder,TextDecoder,structuredClone});
  window.fetch = async input => {
    const path = new URL(input,'http://localhost:8080').pathname;
    return new Response(readFileSync(resolve(root,'.'+path)));
  };
  const errors = [];
  window.addEventListener('error',event => errors.push(event.error || event.message));
  const scripts = [...html.matchAll(/<script defer src="([^"]+)"/g)].map(match => match[1]);
  for (const script of scripts) new vm.Script(readFileSync(resolve(root,'.'+script),'utf8'),{filename:script}).runInContext(dom.getInternalVMContext());
  for (let attempt=0; attempt<100 && !window.document.querySelector('[data-drive-local]'); attempt++) await new Promise(resolve => setTimeout(resolve,10));
  assert.ok(window.document.querySelector('[data-drive-local]'),'local access is available before Google login');
  const welcome = window.document.querySelector('.welcome-card');
  assert.ok(welcome.querySelector('.welcome-actions [data-drive-login]'));
  assert.ok(welcome.querySelector('[data-drive-login] .google-icon'));
  assert.equal(welcome.querySelector('.welcome-divider').textContent,'oppure');
  assert.ok(welcome.querySelector('.welcome-note').textContent.includes('facoltativo'));
  window.document.querySelector('[data-drive-local]').click();
  for (let attempt=0; attempt<100 && !window.document.querySelector('.layout'); attempt++) await new Promise(resolve => setTimeout(resolve,10));
  assert.ok(window.document.querySelector('.layout'),window.document.querySelector('#app').textContent);
  assert.equal(window.document.querySelector('[data-drive-sync]').textContent,'Accedi con Google');
  window.QuadraIphoneBackup.changed();
  assert.ok(window.document.querySelector('[data-iphone-export]'));
  const leaving = new window.Event('beforeunload',{cancelable:true});
  window.dispatchEvent(leaving);
  assert.equal(leaving.defaultPrevented,false);
  window.document.querySelector('[data-iphone-confirm]').click();
  await new Promise(resolve => setTimeout(resolve,0));
  assert.ok(window.document.querySelector('.quadra-dialog'));
  window.document.querySelector('[data-dialog-confirm]').click();
  await new Promise(resolve => setTimeout(resolve,0));
  assert.equal(window.QuadraIphoneBackup.pending(),false);
  window.document.querySelector('[data-nav="settings"]').click();
  assert.ok(window.document.querySelector('#page-content').textContent.includes('Ripristina un archivio completo'));
  assert.ok(window.document.querySelector('.local-folder-card'));
  let authCallback;
  window.google = {accounts:{oauth2:{initTokenClient:options => {
    authCallback = options.callback; return {requestAccessToken() {}};
  }}}};
  window.document.querySelector('[data-drive-sync]').click();
  assert.equal(window.document.querySelector('[data-drive-sync]').getAttribute('aria-busy'),'true');
  assert.ok(window.document.querySelector('[data-drive-sync] .sync-spinner'));
  assert.equal(window.document.querySelector('.toast').textContent,'Sincronizzazione in corso');
  authCallback({error:'Accesso annullato'});
  await new Promise(resolve => setTimeout(resolve,30));
  assert.equal(window.document.querySelector('[data-drive-sync]').disabled,false);
  assert.deepEqual(errors,[]);
  dom.window.close();
});
test('custom dialogs support cancellation, text input and queued confirmations', async () => {
  const dom = new JSDOM('<body><button id="origin">Apri</button></body>',{runScripts:'outside-only'});
  new vm.Script(readFileSync('../dist/online/dialogs.js','utf8')).runInContext(dom.getInternalVMContext());
  const window = dom.window, document = window.document;
  document.querySelector('#origin').focus();
  const cancelled = window.QuadraDialog.confirm('Confermare <contenuto> sicuro?');
  await new Promise(resolve => setTimeout(resolve,0));
  assert.equal(document.querySelector('[data-dialog-message]').textContent,'Confermare <contenuto> sicuro?');
  document.querySelector('.quadra-dialog').dispatchEvent(new window.KeyboardEvent('keydown',{key:'Escape',bubbles:true}));
  assert.equal(await cancelled,false);
  assert.equal(document.activeElement.id,'origin');
  const typed = window.QuadraDialog.prompt('Digita RIPRISTINA');
  const next = window.QuadraDialog.confirm('Seconda conferma');
  await new Promise(resolve => setTimeout(resolve,0));
  assert.equal(document.querySelectorAll('.quadra-dialog').length,1);
  document.querySelector('[data-dialog-input]').value='RIPRISTINA';
  document.querySelector('[data-dialog-confirm]').click();
  assert.equal(await typed,'RIPRISTINA');
  await new Promise(resolve => setTimeout(resolve,0));
  document.querySelector('[data-dialog-confirm]').click();
  assert.equal(await next,true);
  assert.equal(document.querySelector('.quadra-dialog'),null);
  dom.window.close();
});
